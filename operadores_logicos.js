//OPERADORES COMPARACION

let x = 5; //Asignacion

// Operador == compar los valores sea iguales

console.log(x == 6); //False
console.log(x == 5); // True


//Operador === compara el valor y el tipo de dato sean iguales
console.log(x === 5); //True
console.log(x === "5"); //False

// Operador != Diferente
console.log(x != 8); //True
console.log(x != 5); //False

// Operador !== Diferente valor como en el tipo de dato
console.log(x !== 5); // False
console.log(x !== "5"); // True

//Operador > Mayor que
console.log(x > 10); //False
console.log(x > 2); // True

//Operador < Menor que
console.log(x < 10); // True
console.log(x < 2); // False

//Operador >= Mayor o igual que
console.log(x >= 4); //True
console.log(x >= 5); //True
console.log(x >= 6); // False

//Operador <= Menor o igual que
console.log(x <= 4); //False
console.log(x <= 5); //True
console.log(x <= 6); //True